public class QueueCmd extends MusicCommand 
{
public QueueCmd(Bot bot)
    {
        super(bot);
        this.name = "queue";
        this.help = "shows the current queue";
        this.arguments = "[pagenum]";
        this.aliases = bot.getConfig().getAliases(this.name);
        this.bePlaying = true;
        this.botPermissions = new Permission[]{Permission.MESSAGE_ADD_REACTION,Permission.MESSAGE_EMBED_LINKS};
}

    @Override
    public void doCommand(CommandEvent event)
    {
        int pagenum = 1;
        try
        {
            pagenum = Integer.parseInt(event.getArgs());
        }
        catch(NumberFormatException ignore){}
        AudioHandler ah = (AudioHandler)event.getGuild().getAudioManager().getSendingHandler();
        if(ah.getQueue().isEmpty())
        {
            boolean playing = ah.getPlayer().getPlayingTrack() != null;
            event.getChannel().sendMessage(Embeds.nowPlaying(bot, event.getGuild())).queue(m ->
            {
                if(playing)
                    bot.getNowplayingHandler().setLastNPMessage(m);
            });
            return;
        }
        event.getChannel().sendMessage(Embeds.queue(bot, event.getGuild(), pagenum - 1)).queue();
    }
}
